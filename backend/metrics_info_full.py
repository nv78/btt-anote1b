def normalize_task_type_for_metrics(task_type: Optional[str]) -> str:
    """Normalize labels so metrics lines up with ``get_metrics_for_task`` keys."""
    if not task_type:
        return "translation"
    t = str(task_type).lower().strip().replace(" ", "_").replace("-", "_")
    aliases = {
        "ner": "named_entity_recognition",
        "qa": "document_qa",
        "chatbot": "document_qa",
        "prompting": "line_qa",
        "multiclass": "text_classification",
        "classification": "text_classification",
        "geolocation_inference": "geolocation",
        "geo": "geolocation",
        "summerization": "summarization",
        "sum": "summarization",
        "mt": "translation",
        "machine_translation": "translation",
        "reading_comprehension": "document_qa",
        "extractive_qa": "document_qa",
        "span_qa": "document_qa",
        "information_retrieval": "retrieval",
        "rag": "retrieval",
        "multi_label": "text_classification",
        "reasoning": "text_classification",
        "multiple_choice": "text_classification",
        "multilingual_eval": "multilingual",
    }
    return aliases.get(t, t)


def primary_metric_catalog_entry(metric_key: Optional[str]) -> dict:
    """Rich catalog entry for the dataset's primary ``evaluation_metric``."""
    if metric_key is None or metric_key == "":
        return {}
    mk = str(metric_key).lower().strip()
    return dict(METRICS_CATALOG.get(mk) or get_metric_info(mk))


def get_metric_info(metric_name: str) -> dict:
    """Get information about a specific metric."""
    return METRICS_CATALOG.get(
        metric_name,
        {
        "name": metric_name.replace("_", " ").title(),
        "description": "Metric information not available",
        "range": "Unknown",
            "formula": "Unknown",
        },
    )


